# --- Funções de predição ---

def predict_ner(text, tokenizer_obj, model_obj, id_to_tag_map, device, max_length=256):
    encoded = tokenizer_obj(
        text.split(),
        is_split_into_words=True,
        return_tensors="pt",
        padding="max_length",
        truncation=True,
        max_length=max_length
    )
    inputs = {k: v.to(device) for k, v in encoded.items()}

    if 'token_type_ids' not in inputs:
        # Some tokenizers (like BertTokenizerFast) might not generate token_type_ids
        # for is_split_into_words=True unless explicitly handled.
        # BERT models often expect them. Provide a tensor of zeros if missing.
        inputs['token_type_ids'] = torch.zeros_like(inputs['input_ids'])

    with torch.no_grad():
        outputs = model_obj(**inputs)
        predicted_ids_raw = outputs["predictions"]

    predicted_token_ids = predicted_ids_raw.squeeze().cpu().numpy().tolist()
    tokens = tokenizer_obj.convert_ids_to_tokens(inputs["input_ids"].squeeze().tolist())
    word_ids = encoded.word_ids(batch_index=0)

    results = []
    current_word_tokens = []
    current_word_tag = "O"
    previous_word_id = None

    for i, word_id in enumerate(word_ids):
        # Skip special tokens and handle cases where word_id might be None
        if word_id is None or tokens[i] in tokenizer_obj.all_special_tokens:
            if current_word_tokens:
                results.append({"word": "".join(current_word_tokens).replace("##", ""), "tag": current_word_tag})
            current_word_tokens = []
            current_word_tag = "O"
            previous_word_id = word_id
            continue

        token = tokens[i]
        # Ensure predicted_token_ids has an entry for the current index
        if i < len(predicted_token_ids):
            predicted_tag_id = predicted_token_ids[i]
            predicted_tag = id_to_tag_map.get(predicted_tag_id, "O")
        else:
            predicted_tag = "O" # Default to 'O' if no prediction is available (shouldn't happen with padding)


        if word_id != previous_word_id:
            # New word detected
            if current_word_tokens:
                results.append({"word": "".join(current_word_tokens).replace("##", ""), "tag": current_word_tag})
            current_word_tokens = [token]
            current_word_tag = predicted_tag
        else:
            # Same word as previous token
            current_word_tokens.append(token)
            # For multi-token words, take the tag of the first token in the word
            # or if it's a B- tag, keep it. For I-tags, ensure consistency.
            # This logic can be tricky and depends on your tagging scheme (BIO, IOB2, etc.)
            # For simplicity, if the current token has a non-O tag and it's the same word, update the tag.
            # If the current_word_tag is 'O' and predicted_tag is not 'O', update it.
            if current_word_tag == "O" and predicted_tag != "O":
                 current_word_tag = predicted_tag
            elif predicted_tag.startswith("B-"): # If a new B-tag appears within the same word_id, it might indicate an issue or a new entity
                current_word_tag = predicted_tag # Take the new B-tag
            elif predicted_tag.startswith("I-") and not current_word_tag.startswith("B-") and not current_word_tag.startswith("I-"):
                # If current is O but new is I- (shouldn't happen in correct BIO), just set it
                current_word_tag = predicted_tag

        previous_word_id = word_id

    # Add the last accumulated word
    if current_word_tokens:
        results.append({"word": "".join(current_word_tokens).replace("##", ""), "tag": current_word_tag})

    # Post-processing: remove special tokens if any remain in 'word'
    cleaned_results = []
    for entry in results:
        # Remove any remaining BERT special tokens from the word string
        cleaned_word = entry['word'].replace("[CLS]", "").replace("[SEP]", "").replace("[PAD]", "")
        if cleaned_word: # Only add if the word is not empty after cleaning
            cleaned_results.append({"word": cleaned_word, "tag": entry['tag']})

    return cleaned_results

def predict_category(text, tokenizer_obj, model_obj, id_to_label_map, device, max_length=128):
    inputs = tokenizer_obj(text, return_tensors="pt", truncation=True, padding="max_length", max_length=max_length)
    inputs = {k: v.to(device) for k, v in inputs.items()}
    with torch.no_grad():
        outputs = model_obj(**inputs)
        logits = outputs.logits
        predicted_class_id = logits.argmax().item()
    return id_to_label_map.get(predicted_class_id, "N/A")

