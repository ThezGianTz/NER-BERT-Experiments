# 4. Definição do Modelo BERT-CRF para NER
class BertCRFForNER(nn.Module):
    """
    Modelo BERT com uma camada CRF para Reconhecimento de Entidades Nomeadas.
    """
    def __init__(self, num_labels, model_name="neuralmind/bert-base-portuguese-cased"):
        super(BertCRFForNER, self).__init__()
        self.num_labels = num_labels
        self.bert = BertModel.from_pretrained(model_name)
        self.dropout = nn.Dropout(self.bert.config.hidden_dropout_prob)
        self.classifier = nn.Linear(self.bert.config.hidden_size, num_labels)
        self.crf = CRF(num_labels, batch_first=True)

    # CORREÇÃO AQUI: Adicionar token_type_ids ao forward
    def forward(self, input_ids, attention_mask, token_type_ids=None, labels=None):
        # Passar token_type_ids para o BERT se ele for fornecido
        outputs = self.bert(input_ids=input_ids, attention_mask=attention_mask, token_type_ids=token_type_ids)
        sequence_output = self.dropout(outputs.last_hidden_state)
        logits = self.classifier(sequence_output)
        mask = attention_mask.bool()

        loss = None
        if labels is not None:
            labels_for_crf = labels.clone()
            o_tag_id = tag_to_id.get('O', 0)
            labels_for_crf[labels_for_crf == -100] = o_tag_id

            loss = -self.crf(logits, labels_for_crf.long(), mask=mask, reduction="mean")

        predictions_list_of_lists = self.crf.decode(logits, mask=mask)

        predictions_padded = np.full((attention_mask.size(0), attention_mask.size(1)), tag_to_id.get('O', 0), dtype=int)
        if predictions_list_of_lists:
            for i, pred_seq in enumerate(predictions_list_of_lists):
                current_len = attention_mask[i].sum().item()
                copy_len = min(len(pred_seq), current_len)
                predictions_padded[i, :copy_len] = np.array(pred_seq[:copy_len], dtype=int)

        predictions_padded_tensor = torch.tensor(predictions_padded, dtype=torch.long)

        return {"loss": loss, "predictions": predictions_padded_tensor}

# 5. Data Collator Personalizado
def data_collator_custom(features):
    """
    Função para agrupar (collate) os batches de dados, convertendo listas em tensores.
    """
    batch = {}
    batch["input_ids"] = torch.tensor([f["input_ids"] for f in features], dtype=torch.long)
    batch["attention_mask"] = torch.tensor([f["attention_mask"] for f in features], dtype=torch.long)
    # CORREÇÃO AQUI: Incluir token_type_ids se presente nos dados
    if "token_type_ids" in features[0]:
        batch["token_type_ids"] = torch.tensor([f["token_type_ids"] for f in features], dtype=torch.long)
    if "labels" in features[0]:
        batch["labels"] = torch.tensor([f["labels"] for f in features], dtype=torch.long)
    return batch

# 6. Função para Calcular Métricas para NER
def compute_metric1(p, id_to_tag_map, tag_to_id_map, tokenizer_obj):
    """
    Calcula métricas de avaliação para o modelo NER (token-level).
    Esta função é usada no Trainer do Hugging Face.
    """
    labels_batch = p.label_ids
    predictions_batch = p.predictions # Estas já são as previsões decodificadas do CRF (tensor ou numpy array)

    # Garante que predictions_batch é um array numpy
    if isinstance(predictions_batch, torch.Tensor):
        predictions_batch = predictions_batch.cpu().numpy()
    elif not isinstance(predictions_batch, np.ndarray):
        print(f"ERRO INTERNO: predictions_batch em compute_metric1 NÃO é um Tensor nem um array NumPy. Tipo: {type(predictions_batch)}")
        return {"f1": 0.0, "precision": 0.0, "recall": 0.0, "accuracy": 0.0}

    # Assegura que attention_mask_batch é obtida corretamente
    attention_mask_batch = None
    if isinstance(p.inputs, dict) and 'attention_mask' in p.inputs:
        attention_mask_batch = p.inputs['attention_mask']
        if isinstance(attention_mask_batch, torch.Tensor):
            attention_mask_batch = attention_mask_batch.cpu().numpy()
    if attention_mask_batch is None:
        attention_mask_batch = np.ones_like(labels_batch) # Fallback seguro

    true_labels_cleaned = []
    predictions_cleaned = []

    for batch_idx in range(labels_batch.shape[0]):
        true_row = labels_batch[batch_idx]
        pred_row_ids = predictions_batch[batch_idx]
        mask_row = attention_mask_batch[batch_idx]

        for i in range(len(true_row)):
            # Somente considera tokens que não são especiais (-100) e que estão mascarados (mask=1)
            if true_row[i] != -100 and mask_row[i] == 1:
                true_label_id = int(true_row[i])
                pred_label_id = int(pred_row_ids[i]) # Assumindo que pred_row_ids[i] já é um escalar int

                # Mapeia IDs de volta para tags, usando 'O' como fallback seguro
                true_labels_cleaned.append(id_to_tag_map.get(true_label_id, 'O'))
                predictions_cleaned.append(id_to_tag_map.get(pred_label_id, 'O'))

    if not true_labels_cleaned:
        print("AVISO: Nenhum label verdadeiro válido para calcular métricas de NER após filtragem. Retornando 0.0 para todas as métricas.")
        return {"f1": 0.0, "precision": 0.0, "recall": 0.0, "accuracy": 0.0}

    try:
        accuracy_score_val = accuracy_score(true_labels_cleaned, predictions_cleaned)
        precision_score_val, recall_score_val, f1_score_val, _ = precision_recall_fscore_support(
            true_labels_cleaned, predictions_cleaned, average='weighted', zero_division=0
        )

        return {
            "f1": f1_score_val,
            "precision": precision_score_val,
            "recall": recall_score_val,
            "accuracy": accuracy_score_val,
        }

    except ValueError as e:
        print(f"ERRO ao calcular classification_report para NER: {e}")
        return {"f1": 0.0, "precision": 0.0, "recall": 0.0, "accuracy": 0.0}


# 7. Subclasse do Trainer para manipular prediction_step para NER
class MyTrainer(Trainer):
    """
    Subclasse do Trainer para garantir que as previsões do modelo BERT-CRF
    (que já são decodificadas) sejam passadas corretamente para compute_metrics.
    """
    def prediction_step(self, model, inputs, prediction_loss_only, ignore_keys=None):
        model_device = next(model.parameters()).device

        # Move os inputs para o dispositivo correto
        # Remove token_type_ids se não for esperado pelo forward do modelo.
        # No nosso caso, o forward do BertCRFForNER AGORA espera token_type_ids, então não precisa remover aqui.
        for k, v in inputs.items():
            if isinstance(v, torch.Tensor):
                inputs[k] = v.to(model_device)

        with torch.no_grad():
            outputs = model(**inputs)

        loss = outputs.get("loss", None)
        predictions = outputs.get("predictions", None)

        if prediction_loss_only:
            return (loss.detach() if loss is not None else None, None, None)

        return (loss.detach() if loss is not None else None,
                        predictions,
                        inputs["labels"].detach() if "labels" in inputs else None)


