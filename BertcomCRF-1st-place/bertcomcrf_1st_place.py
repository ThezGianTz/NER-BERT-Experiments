# 1. Leitura Arquivo CoNLL em utf-8
def read_conll_file(file_path):
    """
    Lê um arquivo no formato CoNLL e extrai sentenças com suas palavras e tags.

    Args:
        file_path (str): O caminho para o arquivo CoNLL.

    Returns:
        list: Uma lista de dicionários, onde cada dicionário representa uma sentença
              com chaves 'words' (lista de palavras) e 'tags' (lista de tags correspondentes).
    """
    sentences = []
    current_words = []
    current_tags = []
    with open(file_path, 'r', encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if line: # Se a linha não estiver vazia
                parts = line.split()
                if len(parts) >= 4: # Assume formato 'word pos_tag chunk_tag ner_tag'
                    word = parts[0]
                    tag = parts[3] # A quarta coluna é a tag NER
                    current_words.append(word)
                    current_tags.append(tag)
                else:
                    print(f"AVISO: Linha malformada ignorada: '{line}'")
            else: # Linha em branco indica fim de uma sentença
                if current_words:
                    sentences.append({"words": current_words, "tags": current_tags})
                    current_words = []
                    current_tags = []
    # Adiciona a última sentença se o arquivo não terminar com uma linha em branco
    if current_words:
        sentences.append({"words": current_words, "tags": current_tags})
    return sentences

