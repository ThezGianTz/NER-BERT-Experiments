def compute_metrics(p):
    predictions, labels = p
    predictions = np.argmax(predictions, axis=2) # Pega o índice com a maior probabilidade para cada token

    # Remove os labels -100 e as previsões correspondentes
    # Estes são os tokens especiais (CLS, SEP, PAD) ou subtokens que não são o primeiro de uma palavra.
    true_labels = [[id_to_tag[l] for l in label if l != -100] for label in labels]
    true_predictions = [
        [id_to_tag[p] for (p, l) in zip(prediction, label) if l != -100]
        for prediction, label in zip(predictions, labels)
    ]

    # Calcular métricas com seqeval (nível de ENTIDADE)
    # Estas são as métricas mais importantes para NER
    results = seqeval_metric.compute(predictions=true_predictions, references=true_labels, zero_division=0)

    # Calcular métricas token-nível (F1, Recall, Precision, Accuracy)
    # Para as métricas do sklearn, precisamos achatar as listas de tokens e tags.
    flat_true_labels = [item for sublist in true_labels for item in sublist]
    flat_true_predictions = [item for sublist in true_predictions for item in sublist]

    # Converter para IDs para o sklearn
    flat_true_labels_ids = [tag_to_id[tag] for tag in flat_true_labels]
    flat_true_predictions_ids = [tag_to_id[tag] for tag in flat_true_predictions]

    # Acurácia a nível de token
    token_accuracy = accuracy_score(flat_true_labels_ids, flat_true_predictions_ids)

    # Precisão, Recall, F1 a nível de token (weighted average para lidar com desbalanceamento)
    # O 'labels' argumenta garante que todas as classes são consideradas, mesmo que ausentes em um batch.
    precision_token, recall_token, f1_token, _ = precision_recall_fscore_support(
        flat_true_labels_ids, flat_true_predictions_ids,
        labels=list(tag_to_id.values()),
        average='weighted',
        zero_division=0
    )

    return {
        # Métricas a nível de ENTIDADE (seqeval) - mais relevantes para NER
        "overall_precision": results["overall_precision"],
        "overall_recall": results["overall_recall"],
        "overall_f1": results["overall_f1"],
        "overall_accuracy_seqeval": results["overall_accuracy"], # Acurácia como calculada por seqeval

        # Métricas a nível de TOKEN (sklearn) - solicitadas por você
        "token_accuracy": token_accuracy,
        "token_precision_weighted": precision_token,
        "token_recall_weighted": recall_token,
        "token_f1_weighted": f1_token,
    }

