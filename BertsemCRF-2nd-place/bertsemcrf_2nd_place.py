def tokenize_and_align_labels(sentence_data, tokenizer, tag_to_id, max_length=128):
    """
    Tokeniza as palavras de uma sentença e alinha suas tags com os subtokens gerados.

    Args:
        sentence_data (dict): Dicionário com 'words' e 'tags' de uma sentença.
        tokenizer: O tokenizador BERT/Fast.
        tag_to_id (dict): Mapeamento de tags de string para IDs numéricos.
        max_length (int): Comprimento máximo da sequência de tokens.

    Retorna:
        dict: Dicionário contendo 'input_ids', 'attention_mask' e 'labels' (IDs numéricos alinhados).
    """
    # Tokeniza a lista de palavras. is_split_into_words=True é crucial aqui!
    tokenized_inputs = tokenizer(
        sentence_data["words"],
        is_split_into_words=True, # Informa ao tokenizador que a entrada já está pré-dividida em palavras
        truncation=True,          # Trunca sentenças que excedem max_length
        padding="max_length",     # Preenche sentenças menores para max_length
        max_length=max_length,    # Define o comprimento máximo da sequência
        return_tensors='pt'       # Retorna tensores PyTorch
    )

    labels = []
    # word_ids() mapeia cada token/subtoken para o índice da palavra original correspondente.
    # Ex: ["jiboia"] -> ["ji", "##boia"]
    # word_ids() retornaria [0, 0] para esses dois subtokens.
    word_ids = tokenized_inputs.word_ids(batch_index=0) # batch_index=0 pois estamos processando uma sentença por vez aqui

    previous_word_idx = None
    label_ids = []

    for word_idx in word_ids:
        # Se o token é um token especial (CLS, SEP, PAD), word_idx será None.
        # Nesses casos, definimos o label como -100, que será ignorado pela função de perda.
        if word_idx is None:
            label_ids.append(-100)
        # Se este token é o primeiro subtoken de uma nova palavra,
        # atribuímos a tag original da palavra.
        elif word_idx != previous_word_idx:
            # Mapeia a tag original para o ID numérico
            label_ids.append(tag_to_id[sentence_data["tags"][word_idx]])
        # Se este token é um subtoken subsequente da mesma palavra original,
        # também definimos o label como -100.
        # Esta é uma prática padrão para que apenas o primeiro subtoken carregue a tag.
        else:
            label_ids.append(-100)
        previous_word_idx = word_idx

    labels.append(label_ids)

    # Adiciona os labels (tags alinhadas) ao dicionário de entrada tokenizada
    tokenized_inputs["labels"] = torch.tensor(labels) # Converte para tensor

    return {k: v.squeeze(0) for k, v in tokenized_inputs.items()} # Remove dimensão extra de batch

