# 2. Leitura Arquivo CoNLL em utf-8
def read_conll_file(file_path):
    sentences = []
    current_words = []
    current_tags = []
    with open(file_path, 'r', encoding='utf-8') as f:
        for line in f:
            line = line.strip() # Remove espaços em branco e quebras de linha
            if line: # Se a linha não estiver vazia, é uma palavra e sua tag
                parts = line.split()
                # Verifica se a linha tem o formato esperado: WORD -X- _ TAG
                # Baseado na sua imagem, a tag é a 4ª parte (índice 3)
                if len(parts) >= 4:
                    word = parts[0]
                    tag = parts[3]
                    current_words.append(word)
                    current_tags.append(tag)
                else:
                    print(f"AVISO: Linha malformada ignorada: '{line}' no arquivo '{file_path}'")
            else: # Se a linha estiver vazia, é o fim de uma sentença
                if current_words: # Adiciona a sentença atual se houver palavras
                    sentences.append({"words": current_words, "tags": current_tags})
                current_words = []
                current_tags = []
    # Adiciona a última sentença se o arquivo não terminar com uma linha vazia
    if current_words:
        sentences.append({"words": current_words, "tags": current_tags})
    return sentences

