# Função para prever a categoria de uma dada sentença
def predict_category(text, tokenizer, model, id_to_label_map, max_length=128):
    # Tokenizar a sentença de entrada
    inputs = tokenizer(text, return_tensors="pt", truncation=True, padding="max_length", max_length=max_length)
    # Mover os tensores para o mesmo dispositivo do modelo
    inputs = {k: v.to(device) for k, v in inputs.items()}

    with torch.no_grad(): # Desativa o cálculo de gradientes para inferência (apenas para frente)
        outputs = model(**inputs)

    # Obter os logits (saídas brutas do modelo) e encontrar o ID da classe com maior probabilidade
    logits = outputs.logits
    predicted_class_id = logits.argmax().item()

    # Mapear o ID da classe de volta para a label de texto
    return id_to_label_map[predicted_class_id]


