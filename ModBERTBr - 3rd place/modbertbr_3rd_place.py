# --- Definição da classe ModBERTCRFForNER ---
# Esta classe PRECISA ser definida AQUI para que o PyTorch saiba como carregar seu modelo personalizado.
class ModBERTCRFForNER(nn.Module):
    def __init__(self, num_labels, model_name="wallacelw/ModBERTBr"):
        super(ModBERTCRFForNER, self).__init__()
        self.num_labels = num_labels
        # AutoModelForTokenClassification já inclui o BERT base e uma cabeça linear
        self.bert_classifier = AutoModelForTokenClassification.from_pretrained(model_name, num_labels=num_labels, local_files_only=False)
        self.crf = CRF(num_labels, batch_first=True)

    def forward(self, input_ids, attention_mask, token_type_ids=None, labels=None):
        # Inspeciona se o forward do bert_classifier aceita token_type_ids
        bert_classifier_forward_params = inspect.signature(self.bert_classifier.forward).parameters
        accepts_token_type_ids = 'token_type_ids' in bert_classifier_forward_params

        bert_inputs = {
            'input_ids': input_ids,
            'attention_mask': attention_mask,
            'output_hidden_states': False,
            'output_attentions': False,
            'return_dict': True
        }
        if token_type_ids is not None and accepts_token_type_ids:
            bert_inputs['token_type_ids'] = token_type_ids

        outputs = self.bert_classifier(**bert_inputs)
        logits = outputs.logits
        mask = attention_mask.bool()

        loss = None
        # Para inferência, 'labels' geralmente é None. O cálculo da perda só ocorre no treinamento.
        # Este bloco não será executado durante a inferência, mas é mantido para consistência
        # com a definição de classe usada no treinamento.
        if labels is not None:
            # Note: tag_to_id_loaded should be passed or globally accessible if this part is used
            # For this inference script, labels will be None, so this won't be an issue.
            pass

        # A decodificação sempre ocorre para obter as previsões
        predictions_list_of_lists = []
        if logits is not None:
            predictions_list_of_lists = self.crf.decode(logits, mask=mask)

        # Retorna os resultados, para inferência apenas predictions é relevante.
        # predictions_list_of_lists já é o formato correto (lista de listas de IDs).
        return {"loss": loss, "predictions": predictions_list_of_lists}


