# --- 4. Função para Tokenizar e Alinhar Rótulos ---
def tokenize_and_align_labels(sentence_data, tokenizer, tag_to_id, max_length=128):
    """
    Tokeniza palavras e alinha os rótulos de tags para tokens do BERT.
    Tokens especiais (-100) e subtokens subsequentes (-100) são marcados como -100.
    """
    tokenized_inputs = tokenizer(
        sentence_data["words"],
        is_split_into_words=True,
        truncation=True,
        padding="max_length",
        max_length=max_length,
        return_tensors='pt'
    )
    word_ids = tokenized_inputs.word_ids(batch_index=0)
    label_ids = []

    previous_word_idx = None
    for i, word_idx in enumerate(word_ids):
        if word_idx is None:
            label_ids.append(-100) # Token especial (CLS, SEP, PAD)
        elif word_idx != previous_word_idx:
            # Primeiro token de uma nova palavra
            if word_idx < len(sentence_data["tags"]):
                label_ids.append(tag_to_id[sentence_data["tags"][word_idx]])
            else:
                label_ids.append(-100) # Caso word_idx seja inválido
        else:
            label_ids.append(-100) # Subsequente token da mesma palavra
        previous_word_idx = word_idx

    labels_tensor_aligned = torch.tensor(label_ids, dtype=torch.long)

    # Retorna os tensores sem a dimensão do batch para que o Dataset.from_dict possa concatenar corretamente
    return {k: v.squeeze(0) for k, v in tokenized_inputs.items()}, labels_tensor_aligned

