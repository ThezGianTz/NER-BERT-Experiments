# --- 2. Leitura Arquivo CoNLL em utf-8 ---
def read_conll_file(file_path):
    """
    Lê um arquivo no formato CoNLL e extrai sentenças com suas palavras e tags.
    """
    sentences = []
    current_words = []
    current_tags = []
    try:
        with open(file_path, 'r', encoding='utf-8') as f:
            for line in f:
                line = line.strip()
                if line:
                    parts = line.split()
                    if len(parts) >= 4: # Assume formato 'word pos_tag chunk_tag ner_tag'
                        word = parts[0]
                        tag = parts[3] # A quarta coluna é a tag NER
                        current_words.append(word)
                        current_tags.append(tag)
                    else:
                        print(f"AVISO: Linha malformada ignorada: '{line}' no arquivo '{file_path}'")
                else:
                    if current_words:
                        sentences.append({"words": current_words, "tags": current_tags})
                    current_words = []
                    current_tags = []
            if current_words: # Adiciona a última sentença se o arquivo não terminar com uma linha em branco
                sentences.append({"words": current_words, "tags": current_tags})
    except FileNotFoundError:
        print(f"ERRO: O arquivo '{file_path}' não foi encontrado. Por favor, verifique o caminho.")
        return []
    return sentences

