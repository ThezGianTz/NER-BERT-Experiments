# --- 5. Definição do Modelo BERT-CRF para NER (Aprimorado) ---
class ModBERTCRFForNER(nn.Module):
    """
    Modelo BERT (ModernBERT) com uma camada CRF para Reconhecimento de Entidades Nomeadas.
    Utiliza AutoModelForTokenClassification como base.
    """
    def __init__(self, num_labels, model_name="wallacelw/ModBERTBr"):
        super(ModBERTCRFForNER, self).__init__()
        self.num_labels = num_labels
        # Carrega o modelo base (BERT) e sua cabeça de classificação de tokens.
        # AutoModelForTokenClassification já tem uma camada linear no topo.
        self.bert_classifier = AutoModelForTokenClassification.from_pretrained(model_name, num_labels=num_labels)
        # O dropout já está embutido no AutoModelForTokenClassification, então não precisamos de um extra aqui.
        self.crf = CRF(num_labels, batch_first=True)

    def forward(self, input_ids, attention_mask, token_type_ids=None, labels=None):
        # Only pass token_type_ids if it's not None
        if token_type_ids is not None:
            outputs = self.bert_classifier(
                input_ids=input_ids,
                attention_mask=attention_mask,
                token_type_ids=token_type_ids,
                output_hidden_states=False,
                output_attentions=False,
                return_dict=True
            )
        else:
             outputs = self.bert_classifier(
                input_ids=input_ids,
                attention_mask=attention_mask,
                output_hidden_states=False,
                output_attentions=False,
                return_dict=True
            )

        # logits já vêm da camada linear do AutoModelForTokenClassification
        logits = outputs.logits
        mask = attention_mask.bool() # Máscara para o CRF

        loss = None
        if labels is not None:
            # Para o CRF, precisamos que os labels de padding (-100) sejam um ID de tag válido,
            # geralmente a tag 'O'. A máscara de atenção lida com isso.
            labels_for_crf = labels.clone()
            o_tag_id = tag_to_id.get('O', 0) # Garante que 'O' seja mapeado para um ID válido
            labels_for_crf[labels_for_crf == -100] = o_tag_id

            # O CRF calcula a perda negativa do log-likelihood
            loss = -self.crf(logits, labels_for_crf.long(), mask=mask, reduction="mean")

        # Decodifica a sequência de tags usando o algoritmo Viterbi
        predictions_list_of_lists = self.crf.decode(logits, mask=mask)

        # Converte a lista de listas de previsões em um tensor preenchido com o ID da tag 'O'
        # para que todas as sequências tenham o mesmo comprimento para serem retornadas pelo Trainer.
        # Isso é crucial porque o Trainer espera um tensor para 'predictions'.
        predictions_padded = np.full((attention_mask.size(0), attention_mask.size(1)), tag_to_id.get('O', 0), dtype=int)
        if predictions_list_of_lists:
            for i, pred_seq in enumerate(predictions_list_of_lists):
                current_len = attention_mask[i].sum().item() # Comprimento real da sequência tokenizada
                copy_len = min(len(pred_seq), current_len) # Garante que não copiamos mais do que o real
                predictions_padded[i, :copy_len] = np.array(pred_seq[:copy_len], dtype=int)

        predictions_padded_tensor = torch.tensor(predictions_padded, dtype=torch.long)

        return {"loss": loss, "predictions": predictions_padded_tensor}

# 6. Data Collator Personalizado (adaptado para token_type_ids)
def data_collator_custom(features):
    """
    Função para agrupar (collate) os batches de dados, convertendo listas em tensores.
    """
    batch = {}
    batch["input_ids"] = torch.tensor([f["input_ids"] for f in features], dtype=torch.long)
    batch["attention_mask"] = torch.tensor([f["attention_mask"] for f in features], dtype=torch.long)

    # Adiciona 'token_type_ids' apenas se a coluna existir nos dados do batch
    if 'token_type_ids' in features[0]: # Verifica se o primeiro elemento tem a chave
        batch["token_type_ids"] = torch.tensor([f["token_type_ids"] for f in features], dtype=torch.long)

    if "labels" in features[0]:
        batch["labels"] = torch.tensor([f["labels"] for f in features], dtype=torch.long)
    return batch


# 7. Função para Calcular Métricas para NER (adaptada para CRF)
# O `seqeval_metric` precisa ser carregado fora da função para ser reutilizado
seqeval_metric = evaluate.load("seqeval")

def compute_metrics_ner_crf(p, id_to_tag_map, tag_to_id_map):
    """
    Calcula métricas de avaliação para o modelo NER com CRF (token-level e entity-level).
    Esta função é usada no Trainer do Hugging Face.
    As previsões (p.predictions) já vêm decodificadas do CRF.
    """
    labels_batch = p.label_ids # Ground truth labels
    predictions_batch = p.predictions # Predictions from CRF (already integer IDs)

    # Assegura que predictions_batch e labels_batch são arrays numpy
    if isinstance(predictions_batch, torch.Tensor):
        predictions_batch = predictions_batch.cpu().numpy()
    if isinstance(labels_batch, torch.Tensor):
        labels_batch = labels_batch.cpu().numpy()

    # Assegura que attention_mask_batch é obtida corretamente
    # p.inputs é um dicionário contendo os tensores de entrada originais
    attention_mask_batch = None
    if isinstance(p.inputs, dict) and 'attention_mask' in p.inputs:
        attention_mask_batch = p.inputs['attention_mask']
        if isinstance(attention_mask_batch, torch.Tensor):
            attention_mask_batch = attention_mask_batch.cpu().numpy()
    if attention_mask_batch is None:
        attention_mask_batch = np.ones_like(labels_batch) # Fallback seguro

    true_labels_cleaned = []
    predictions_cleaned = []

    for batch_idx in range(labels_batch.shape[0]):
        true_row = labels_batch[batch_idx]
        pred_row_ids = predictions_batch[batch_idx]
        mask_row = attention_mask_batch[batch_idx]

        for i in range(len(true_row)):
            # Somente considera tokens que não são especiais (-100) e que estão mascarados (mask=1)
            if true_row[i] != -100 and mask_row[i] == 1:
                true_label_id = int(true_row[i])
                pred_label_id = int(pred_row_ids[i])

                true_labels_cleaned.append(id_to_tag_map.get(true_label_id, 'O'))
                predictions_cleaned.append(id_to_tag_map.get(pred_label_id, 'O'))

    if not true_labels_cleaned:
        print("AVISO: Nenhum label verdadeiro válido para calcular métricas de NER após filtragem. Retornando 0.0 para todas as métricas.")
        return {"f1": 0.0, "precision": 0.0, "recall": 0.0, "accuracy": 0.0}


    true_predictions_seqeval = []
    true_labels_seqeval = []

    for batch_idx in range(labels_batch.shape[0]):
        current_sentence_true_labels = []
        current_sentence_predictions = []
        true_row = labels_batch[batch_idx]
        pred_row_ids = predictions_batch[batch_idx]
        mask_row = attention_mask_batch[batch_idx]

        for i in range(len(true_row)):
            if true_row[i] != -100 and mask_row[i] == 1:
                current_sentence_true_labels.append(id_to_tag_map.get(int(true_row[i]), 'O'))
                current_sentence_predictions.append(id_to_tag_map.get(int(pred_row_ids[i]), 'O'))

        if current_sentence_true_labels: # Adiciona apenas se a sentença tiver labels válidos
            true_labels_seqeval.append(current_sentence_true_labels)
            true_predictions_seqeval.append(current_sentence_predictions)

    results = seqeval_metric.compute(predictions=true_predictions_seqeval, references=true_labels_seqeval, zero_division=0)

    # Calcular accuracy a nível de token
    token_accuracy = accuracy_score(true_labels_cleaned, predictions_cleaned)

    # Calcular precision, recall, f1 a nível de token (weighted)
    # Convertendo de volta para IDs para scikit-learn
    flat_true_labels_ids = [tag_to_id_map[tag] for tag in true_labels_cleaned]
    flat_predictions_ids = [tag_to_id_map[tag] for tag in predictions_cleaned]

    precision_token, recall_token, f1_token, _ = precision_recall_fscore_support(
        flat_true_labels_ids, flat_predictions_ids,
        average='weighted',
        zero_division=0
    )

    return {
        "overall_precision": results["overall_precision"],
        "overall_recall": results["overall_recall"],
        "overall_f1": results["overall_f1"],
        "overall_accuracy_seqeval": results["overall_accuracy"], # Accuracy from seqeval (entity-level)
        "token_accuracy": token_accuracy, # Token-level accuracy
        "token_precision_weighted": precision_token,
        "token_recall_weighted": recall_token,
        "token_f1_weighted": f1_token,
    }


# 8. Subclasse do Trainer para manipular prediction_step para NER com CRF
class MyTrainer(Trainer):
    """
    Subclasse do Trainer para garantir que as previsões do modelo BERT-CRF
    (que já são decodificadas pelo CRF no forward do modelo) sejam passadas
    corretamente para compute_metrics.
    """
    def prediction_step(self, model, inputs, prediction_loss_only, ignore_keys=None):
        model_device = next(model.parameters()).device

        # Move os inputs para o dispositivo correto
        for k, v in inputs.items():
            if isinstance(v, torch.Tensor):
                inputs[k] = v.to(model_device)

        with torch.no_grad():
            # Only pass token_type_ids if it exists in inputs
            if 'token_type_ids' in inputs:
                 outputs = model(input_ids=inputs['input_ids'], attention_mask=inputs['attention_mask'], token_type_ids=inputs['token_type_ids'])
            else:
                 outputs = model(input_ids=inputs['input_ids'], attention_mask=inputs['attention_mask'])


        loss = outputs.get("loss", None)
        # As previsões já são os IDs decodificados do CRF
        predictions = outputs.get("predictions", None)

        if prediction_loss_only:
            return (loss.detach() if loss is not None else None, None, None)

        return (loss.detach() if loss is not None else None,
                predictions, # Passa as previsões já decodificadas
                inputs["labels"].detach() if "labels" in inputs else None)


